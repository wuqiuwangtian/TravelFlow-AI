"""夜间延误与次日预约的隔离样本。"""

from app.domain.itinerary import (
    Booking,
    BudgetItem,
    DayPlan,
    ExpenseCreate,
    Itinerary,
    ReplanInput,
    ScheduledActivity,
)
from app.services.replan_service import set_replan_context
from app.services.travel_service import add_expense


def linked_itinerary(*, early_booking=False, with_receipt=False, optional_stop=False):
    plan = Itinerary(
        days=[
            DayPlan(
                day=1,
                title="夜间抵达",
                activities=[
                    ScheduledActivity(
                        id="past",
                        title="已逛完的故宫",
                        place_name="故宫",
                        city="北京",
                        start_time="10:00",
                        duration_minutes=90,
                        progress="completed",
                    ),
                    ScheduledActivity(
                        id="station",
                        title="车站出发",
                        progress="in_progress",
                        place_name="北京站",
                        city="北京",
                        kind="station",
                        start_time="22:00",
                        duration_minutes=20,
                    ),
                    ScheduledActivity(
                        id="night",
                        title="夜间散步",
                        place_name="东街",
                        city="北京",
                        start_time="23:00",
                        duration_minutes=60,
                        transport_minutes=20,
                        cost=10,
                        cost_basis="total",
                        cost_source="estimate",
                    ),
                    ScheduledActivity(
                        id="hotel-one",
                        title="入住示例酒店",
                        place_name="示例酒店",
                        city="北京",
                        kind="hotel",
                        start_time="00:30",
                        start_day_offset=1,
                        duration_minutes=30,
                        transport_minutes=30,
                        cost=300,
                        cost_basis="total",
                        cost_source="estimate",
                    ),
                ],
            ),
            DayPlan(
                day=2,
                title="次日游览",
                activities=[
                    ScheduledActivity(
                        id="park",
                        title="公园漫步",
                        place_name="示例公园",
                        city="北京",
                        start_time="08:00",
                        duration_minutes=60,
                        transport_minutes=30,
                        cost=20,
                        cost_basis="total",
                        cost_source="manual",
                    ),
                    ScheduledActivity(
                        id="museum",
                        title="预约展览",
                        place_name="示例展览馆",
                        city="北京",
                        start_time="09:00" if early_booking else "14:00",
                        duration_minutes=60,
                        transport_minutes=30,
                        booking=Booking(
                            start_time="09:00" if early_booking else "14:00", duration_minutes=60
                        ),
                    ),
                    ScheduledActivity(
                        id="hotel-two",
                        title="返回示例酒店",
                        place_name="示例酒店",
                        city="北京",
                        kind="hotel",
                        start_time="17:00",
                        duration_minutes=30,
                        transport_minutes=30,
                        cost=300,
                        cost_basis="total",
                        cost_source="estimate",
                    ),
                ],
            ),
            DayPlan(
                day=3,
                title="后天保持原样",
                activities=[
                    ScheduledActivity(
                        id="third",
                        title="后天景点",
                        place_name="第三天公园",
                        start_time="09:00",
                        duration_minutes=60,
                    )
                ],
                warnings=["原有提示"],
            ),
        ]
    )
    if optional_stop:
        plan.days[1].activities.insert(
            1,
            ScheduledActivity(
                id="optional",
                title="可选绕路公园",
                place_name="另一个公园",
                city="北京",
                start_time="10:00",
                duration_minutes=600,
                transport_minutes=30,
            ),
        )
    plan.budget_items.append(
        BudgetItem(
            id="stay-park",
            title="公园门票",
            category="ticket",
            day=2,
            activity_id="park",
            source="activity",
            planned_cents=2000,
        )
    )
    add_expense(
        plan,
        ExpenseCreate(
            title="预付公园门票",
            amount="20",
            category="ticket",
            day=2,
            activity_id="park",
            budget_item_id="stay-park",
            settles_budget=True,
            notes="已付款项目不能自动精简",
            receipt_ids=["00000000000000000000000000000001"] if with_receipt else [],
            request_id="fixture-linked-expense",
        ),
    )
    set_replan_context(
        plan,
        1,
        ReplanInput(
            activity_id="station",
            time="23:30",
            end_time="03:00",
            end_day_offset=1,
            end_activity_id="hotel-one",
        ),
    )
    return plan
